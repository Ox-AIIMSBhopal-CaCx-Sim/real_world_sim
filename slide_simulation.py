def cyto_sample_generator(env, params, cyto_processing_queue):
    """
    Generate cytology samples and add them to the processing queue.
    Samples arrive only during working hours (Mon-Sat, 9 AM - 4 PM).
    """
    slide_id = 1
    
    while True:
        # Check if we're in working hours
        if not is_working_hours(env):
            # Wait until next working time
            wait_time = get_next_working_time(env)
            yield env.timeout(wait_time)
            continue
        
        # Generate Pap slides
        for _ in range(params['simulation']['pap_per_day']):
            is_positive = random.random() < params['pap_positive_rate']
            slide = CytoSlide(
                id=slide_id,
                is_pap=True,
                is_positive=is_positive,
                arrival_time=env.now
            )
            cyto_processing_queue.append(slide)
            print(f"[{env.now:.2f}] Pap slide {slide_id} arrived (Positive: {is_positive})")
            slide_id += 1
        
        # Generate Non-Pap slides
        for _ in range(params['simulation']['non_pap_per_day']):
            slide = CytoSlide(
                id=slide_id,
                is_pap=False,
                arrival_time=env.now
            )
            cyto_processing_queue.append(slide)
            print(f"[{env.now:.2f}] Non-Pap slide {slide_id} arrived")
            slide_id += 1
        
        # Wait for the rest of the day (spread arrivals throughout the day)
        # Arrivals happen once per day
        yield env.timeout(1)  # 1 day


