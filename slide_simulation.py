def is_working_hours(env):
    """
    Check if current simulation time is within working hours:
    Monday to Saturday, 9 AM to 4 PM
    """
    # Get current day and time
    current_day = int(env.now) % 7  # 0 = Monday, 6 = Sunday
    current_hour = (env.now % 1) * 24  # Hour of the day (0-24)
    
    # Check if it's Monday to Saturday (0-5)
    is_working_day = current_day < 6
    
    # Check if it's between 9 AM and 4 PM
    is_working_time = 9 <= current_hour < 16
    
    return is_working_day and is_working_time

def get_next_working_time(env):
    """
    Calculate the next working time if current time is outside working hours
    """
    current_day = int(env.now) % 7
    current_hour = (env.now % 1) * 24
    
    # If it's Sunday (day 6), wait until Monday 9 AM
    if current_day == 6:
        hours_until_monday_9am = (24 - current_hour) + 9
        return hours_until_monday_9am / 24
    
    # If it's after 4 PM, wait until next day 9 AM
    if current_hour >= 16:
        hours_until_next_9am = (24 - current_hour) + 9
        return hours_until_next_9am / 24
    
    # If it's before 9 AM, wait until 9 AM today
    if current_hour < 9:
        return (9 - current_hour) / 24
    
    return 0

