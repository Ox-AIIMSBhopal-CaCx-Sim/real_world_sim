def run_simulation(params):
    """
    Run the cytology department simulation.
    """
    # Create SimPy environment
    env = simpy.Environment()
    
    # Create resources
    cytotechnicians = simpy.Resource(env, capacity=params['Staff']['num_cytotechnicians'])
    cytopathologists = simpy.Resource(env, capacity=params['Staff']['num_cytopathologists'])
    
    # Create queues
    cyto_processing_queue = []
    cyto_reporting_queue = []
    
    # Results storage
    results = []
    
    # Start processes
    env.process(cyto_sample_generator(env, params, cyto_processing_queue))
    env.process(cyto_sample_processor(env, params, cyto_processing_queue, cyto_reporting_queue, cytotechnicians))
    env.process(cyto_sample_reporter(env, params, cyto_reporting_queue, cytopathologists, results))
    
    # Run simulation
    run_time = params['simulation']['run_time']
    print(f"\n{'='*60}")
    print(f"Starting Cytology Department Simulation")
    print(f"Run time: {run_time} days")
    print(f"{'='*60}\n")
    
    env.run(until=run_time)
    
    print(f"\n{'='*60}")
    print(f"Simulation Complete")
    print(f"Total slides processed: {len(results)}")
    print(f"{'='*60}\n")
    
    # Convert results to DataFrame
    df_results = pd.DataFrame(results)
    
    if len(results) > 0:
        print("\nSummary Statistics:")
        print(f"Average Turnaround Time: {df_results['turnaround_time'].mean():.2f} days")
        print(f"Median Turnaround Time: {df_results['turnaround_time'].median():.2f} days")
        print(f"Min Turnaround Time: {df_results['turnaround_time'].min():.2f} days")
        print(f"Max Turnaround Time: {df_results['turnaround_time'].max():.2f} days")
    
    return df_results

