def cyto_sample_processor(env, params, cyto_processing_queue, cyto_reporting_queue, cytotechnicians):
    """
    Process cytology slides from the processing queue.
    Requires a cytotechnician resource.
    """
    while True:
        if len(cyto_processing_queue) > 0:
            slide = cyto_processing_queue.pop(0)
            
            # Request a cytotechnician
            with cytotechnicians.request() as request:
                yield request
                
                slide.start_processing_time = env.now
                print(f"[{env.now:.2f}] Started processing slide {slide.id}")
                
                # Processing time (convert minutes to days)
                processing_time = params['processing']['cyto_slides'] / (60 * 24)
                yield env.timeout(processing_time)
                
                # Move to reporting queue
                cyto_reporting_queue.append(slide)
                print(f"[{env.now:.2f}] Finished processing slide {slide.id}, moved to reporting")
        else:
            # Wait a bit before checking again
            yield env.timeout(0.01)

def cyto_sample_reporter(env, params, cyto_reporting_queue, cytopathologists, results):
    """
    Report on cytology slides from the reporting queue.
    Requires a cytopathologist resource.
    """
    while True:
        if len(cyto_reporting_queue) > 0:
            slide = cyto_reporting_queue.pop(0)
            
            # Request a cytopathologist
            with cytopathologists.request() as request:
                yield request
                
                slide.start_reporting_time = env.now
                print(f"[{env.now:.2f}] Started reporting slide {slide.id}")
                
                # Reporting time - using lognormal distribution
                mean = params['reporting']['cyto_slide_distribution']['mean']
                sd = params['reporting']['cyto_slide_distribution']['sd']
                reporting_minutes = np.random.lognormal(mean, sd)
                reporting_time = reporting_minutes / (60 * 24)  # Convert to days
                
                yield env.timeout(reporting_time)
                
                slide.exit_time = env.now
                
                # Calculate turnaround time
                turnaround_time = slide.exit_time - slide.arrival_time
                
                # Store results
                results.append({
                    'slide_id': slide.id,
                    'slide_type': 'Pap' if slide.is_pap else 'Non-Pap',
                    'is_positive': slide.is_positive,
                    'arrival_time': slide.arrival_time,
                    'start_processing_time': slide.start_processing_time,
                    'start_reporting_time': slide.start_reporting_time,
                    'exit_time': slide.exit_time,
                    'turnaround_time': turnaround_time
                })
                
                print(f"[{env.now:.2f}] Finished reporting slide {slide.id} (TAT: {turnaround_time:.2f} days)")
        else:
            # Wait a bit before checking again
            yield env.timeout(0.01)

